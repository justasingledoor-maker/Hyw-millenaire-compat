"""
Armour generator for the Cultures Armory (an Epic Knights add-on).

A model is a tree of parts (Minecraft's humanoid parts and children) made of boxes, written once here. From it this
module generates the Java LayerDefinition, packs every box's texture area, paints the textures face by face (so the art
always lines up with the geometry), and exports a JSON description for the three.js preview (tools/preview.html).

Minecraft's box texture layout (ModelPart.Cube, 1.21.1), for a box of size w, h, d at texOffs (u, v):
  top strip (v .. v+d):        [d gap][top w x d][bottom w x d]
  side strip (v+d .. v+d+h):   [right d][front w][left d][back w]   (right/left: the wearer's)
The side strip runs continuously round the box (right side back->front, front right->left, left side front->back,
back left->right), so patterns can be painted round it without seams. Top and bottom: rows run back (top) to front.
"""
import json
import os
import random

from PIL import Image


class Cube:
    def __init__(self, origin, size, inflate=0.0, paint=None, tag=""):
        self.origin = tuple(float(c) for c in origin)
        self.size = tuple(int(s) for s in size)
        assert all(abs(float(s) - int(s)) < 1e-9 for s in size), "box sizes must be whole texels"
        self.inflate = float(inflate)
        self.paint = paint
        self.tag = tag
        self.uv = None

    @property
    def footprint(self):
        w, h, d = self.size
        return 2 * (d + w), d + h


class Part:
    def __init__(self, name, pivot=(0, 0, 0), rot=(0, 0, 0), cubes=(), children=()):
        self.name = name
        self.pivot = tuple(float(c) for c in pivot)
        self.rot = tuple(float(c) for c in rot)
        self.cubes = list(cubes)
        self.children = list(children)

    def walk(self):
        yield self
        for c in self.children:
            yield from c.walk()


ROOT_PARTS = {
    "head": (0, 0, 0), "hat": (0, 0, 0), "body": (0, 0, 0),
    "right_arm": (-5, 2, 0), "left_arm": (5, 2, 0), "right_leg": (-1.9, 12, 0), "left_leg": (1.9, 12, 0),
}


class Model:
    def __init__(self, java_name, location, parts, tex=(64, 64)):
        """parts: {root part name: Part} for the parts this armour uses (the rest are added empty)."""
        self.java_name = java_name
        self.location = location
        self.tex = tex
        self.roots = []
        for name, pivot in ROOT_PARTS.items():
            p = parts.get(name) or Part(name)
            p.name = name
            p.pivot = tuple(float(c) for c in pivot)
            self.roots.append(p)

    def cubes(self):
        for r in self.roots:
            for p in r.walk():
                for c in p.cubes:
                    yield p, c

    def pack(self):
        """Shelf-packs every box's texture area (tallest first)."""
        W, H = self.tex
        items = sorted((c for _, c in self.cubes()), key=lambda c: (-c.footprint[1], -c.footprint[0]))
        x = y = shelf = 0
        for c in items:
            fw, fh = c.footprint
            if x + fw > W:
                x, y, shelf = 0, y + shelf, 0
            if fw > W or y + fh > H:
                raise ValueError(f"{self.java_name}: texture {W}x{H} too small for the boxes")
            c.uv = (x, y)
            x += fw
            shelf = max(shelf, fh)

    # ------------------------------------------------------------------ java

    def java(self, package):
        out = [f"package {package};", "",
               "import net.minecraft.client.model.geom.PartPose;",
               "import net.minecraft.client.model.geom.builders.CubeDeformation;",
               "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
               "import net.minecraft.client.model.geom.builders.LayerDefinition;",
               "import net.minecraft.client.model.geom.builders.MeshDefinition;",
               "import net.minecraft.client.model.geom.builders.PartDefinition;", "",
               "/** Generated by armory/tools (do not edit by hand): the " + self.location + " armour model. */",
               f"public final class {self.java_name} {{",
               f"    private {self.java_name}() {{}}", "",
               "    public static LayerDefinition createLayer() {",
               "        MeshDefinition mesh = new MeshDefinition();",
               "        PartDefinition root = mesh.getRoot();"]

        def f(v):
            s = repr(round(float(v), 4))
            return s + "F"

        def cubes(p):
            if not p.cubes:
                return "CubeListBuilder.create()"
            s = "CubeListBuilder.create()"
            for c in p.cubes:
                (x, y, z), (w, h, d) = c.origin, c.size
                s += (f"\n                .texOffs({c.uv[0]}, {c.uv[1]}).addBox({f(x)}, {f(y)}, {f(z)}, {f(w)}, {f(h)}, {f(d)}, "
                      f"new CubeDeformation({f(c.inflate)}))")
            return s

        def pose(p):
            (x, y, z), (a, b, c) = p.pivot, p.rot
            if a == b == c == 0:
                return f"PartPose.offset({f(x)}, {f(y)}, {f(z)})"
            return f"PartPose.offsetAndRotation({f(x)}, {f(y)}, {f(z)}, {f(a)}, {f(b)}, {f(c)})"

        counter = [0]

        def emit(p, parent_var):
            var = "p" + str(counter[0])
            counter[0] += 1
            out.append(f"        PartDefinition {var} = {parent_var}.addOrReplaceChild(\"{p.name}\", {cubes(p)},\n                {pose(p)});")
            for ch in p.children:
                emit(ch, var)

        for r in self.roots:
            emit(r, "root")
        out += [f"        return LayerDefinition.create(mesh, {self.tex[0]}, {self.tex[1]});", "    }", "}", ""]
        return "\n".join(out)

    # ------------------------------------------------------------------ preview

    def preview_json(self):
        def part(p):
            return {"name": p.name, "pivot": p.pivot, "rot": p.rot,
                    "cubes": [{"origin": c.origin, "size": c.size, "inflate": c.inflate, "uv": c.uv} for c in p.cubes],
                    "children": [part(ch) for ch in p.children]}
        return {"tex": self.tex, "parts": [part(r) for r in self.roots]}


# ---------------------------------------------------------------------- painting

class Canvas:
    """The texture being painted: colour pixels, each either dyeable (the tinted base layer) or not (the overlay)."""

    def __init__(self, size):
        self.W, self.H = size
        self.px = {}

    def set(self, x, y, rgb, dye=False):
        if 0 <= x < self.W and 0 <= y < self.H and rgb is not None:
            self.px[(x, y)] = (tuple(rgb), dye)

    def layers(self, dyeable):
        """(base, overlay) RGBA images: dyeable pixels go to the base as grey (tinted in game), the rest to the overlay."""
        base = Image.new("RGBA", (self.W, self.H), (0, 0, 0, 0))
        over = Image.new("RGBA", (self.W, self.H), (0, 0, 0, 0))
        for (x, y), (rgb, dye) in self.px.items():
            if dye and dyeable:
                g = rgb[0]
                base.putpixel((x, y), (g, g, g, 255))
            else:
                over.putpixel((x, y), rgb + (255,))
        return base, over

    def composite(self, tint):
        """What the game shows with the given dye colour (for previews)."""
        img = Image.new("RGBA", (self.W, self.H), (0, 0, 0, 0))
        for (x, y), (rgb, dye) in self.px.items():
            if dye:
                g = rgb[0] / 255.0
                img.putpixel((x, y), (int(tint[0] * g), int(tint[1] * g), int(tint[2] * g), 255))
            else:
                img.putpixel((x, y), rgb + (255,))
        return img


class Faces:
    """The faces of one box on the canvas, with the box's size: what a painter draws on."""

    def __init__(self, canvas, cube, scale=1):
        """scale: texels per model unit (2 draws the box at twice the vanilla density, on a canvas twice the layout)."""
        self.c = canvas
        self.cube = cube
        self.w, self.h, self.d = (k * scale for k in cube.size)
        self.u, self.v = (k * scale for k in cube.uv)
        self.strip_w = 2 * (self.w + self.d)
        self.rng = random.Random(hash((cube.uv, cube.size)) & 0xffffffff)

    # side strip: s runs round the box (0 .. strip_w), t from the top (0 .. h)
    def side(self, s, t, rgb, dye=False):
        if 0 <= s < self.strip_w and 0 <= t < self.h:
            self.c.set(self.u + s, self.v + self.d + t, rgb, dye)

    def face_of(self, s):
        """Which face a strip column is on, and the column within it: right, front, left, back."""
        w, d = self.w, self.d
        if s < d:
            return "right", s
        if s < d + w:
            return "front", s - d
        if s < d + w + d:
            return "left", s - d - w
        return "back", s - d - w - d

    def face(self, name, i, t, rgb, dye=False):
        """Column i (0 at the left of the face as seen from outside) and row t (from the top) of one side face."""
        off = {"right": 0, "front": self.d, "left": self.d + self.w, "back": self.d + self.w + self.d}[name]
        width = self.d if name in ("right", "left") else self.w
        if 0 <= i < width:
            self.side(off + i, t, rgb, dye)

    def top(self, i, j, rgb, dye=False):
        """The box's top in the world (j = 0 at the back)."""
        if 0 <= i < self.w and 0 <= j < self.d:
            self.c.set(self.u + self.d + i, self.v + j, rgb, dye)

    def bottom(self, i, j, rgb, dye=False):
        if 0 <= i < self.w and 0 <= j < self.d:
            self.c.set(self.u + self.d + self.w + i, self.v + j, rgb, dye)

    def noise(self, rgb, amount=6):
        if rgb is None:
            return None
        n = self.rng.randint(-amount, amount)
        return tuple(max(0, min(255, c + n)) for c in rgb)


def paint_model(model):
    canvas = Canvas(model.tex)
    for _, c in model.cubes():
        if c.paint:
            c.paint(Faces(canvas, c))
    return canvas


def write_png(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)


def write_text(text, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def write_json(obj, path):
    write_text(json.dumps(obj, indent=2) + "\n", path)
